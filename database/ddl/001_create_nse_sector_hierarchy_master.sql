PROMPT Creating NSE_SECTOR_HIERARCHY_MASTER and related indexes/view

CREATE TABLE NSE_SECTOR_HIERARCHY_MASTER (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARENT_SECTOR       VARCHAR2(100) NOT NULL,
    INDUSTRY_SECTOR     VARCHAR2(150) NOT NULL,
    SUB_SECTOR          VARCHAR2(200) NOT NULL,
    SYMBOL              VARCHAR2(50)  NOT NULL,
    EXCHANGE            VARCHAR2(20)  DEFAULT 'NSE' NOT NULL,
    SOURCE_NAME         VARCHAR2(100),
    SOURCE_FILE         VARCHAR2(255),
    EFFECTIVE_DATE      DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    IS_ACTIVE           CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP,
    CREATED_BY          VARCHAR2(100) DEFAULT USER,
    UPDATED_BY          VARCHAR2(100),
    CONSTRAINT CK_NSE_SECTOR_HIER_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N')),
    CONSTRAINT UK_NSE_SECTOR_HIER UNIQUE (
        PARENT_SECTOR,
        INDUSTRY_SECTOR,
        SUB_SECTOR,
        SYMBOL,
        EXCHANGE
    )
);

CREATE INDEX IDX_NSE_SECTOR_HIER_PARENT
ON NSE_SECTOR_HIERARCHY_MASTER (PARENT_SECTOR, IS_ACTIVE);

CREATE INDEX IDX_NSE_SECTOR_HIER_INDUSTRY
ON NSE_SECTOR_HIERARCHY_MASTER (PARENT_SECTOR, INDUSTRY_SECTOR, IS_ACTIVE);

CREATE INDEX IDX_NSE_SECTOR_HIER_SUB
ON NSE_SECTOR_HIERARCHY_MASTER (PARENT_SECTOR, INDUSTRY_SECTOR, SUB_SECTOR, IS_ACTIVE);

CREATE INDEX IDX_NSE_SECTOR_HIER_SYMBOL
ON NSE_SECTOR_HIERARCHY_MASTER (SYMBOL, EXCHANGE, IS_ACTIVE);

COMMENT ON TABLE NSE_SECTOR_HIERARCHY_MASTER IS 'Master hierarchy map: Parent Sector -> Industry/Sector -> Sub-Sector -> Symbol';
COMMENT ON COLUMN NSE_SECTOR_HIERARCHY_MASTER.PARENT_SECTOR IS 'Top-level parent sector';
COMMENT ON COLUMN NSE_SECTOR_HIERARCHY_MASTER.INDUSTRY_SECTOR IS 'Industry or sector under parent sector';
COMMENT ON COLUMN NSE_SECTOR_HIERARCHY_MASTER.SUB_SECTOR IS 'Sub-sector under industry/sector';
COMMENT ON COLUMN NSE_SECTOR_HIERARCHY_MASTER.SYMBOL IS 'Normalized NSE/BSE symbol token';
COMMENT ON COLUMN NSE_SECTOR_HIERARCHY_MASTER.EXCHANGE IS 'Exchange code, default NSE';
COMMENT ON COLUMN NSE_SECTOR_HIERARCHY_MASTER.IS_ACTIVE IS 'Y when hierarchy row is active';
COMMENT ON COLUMN NSE_SECTOR_HIERARCHY_MASTER.SOURCE_NAME IS 'Logical source label for ingestion';
COMMENT ON COLUMN NSE_SECTOR_HIERARCHY_MASTER.SOURCE_FILE IS 'Original source file name';

CREATE OR REPLACE VIEW VW_NSE_SECTOR_HIERARCHY_ACTIVE AS
SELECT
    PARENT_SECTOR,
    INDUSTRY_SECTOR,
    SUB_SECTOR,
    SYMBOL,
    EXCHANGE,
    EFFECTIVE_DATE
FROM NSE_SECTOR_HIERARCHY_MASTER
WHERE IS_ACTIVE = 'Y';

COMMENT ON TABLE VW_NSE_SECTOR_HIERARCHY_ACTIVE IS 'Read-only active hierarchy view for API reads';
