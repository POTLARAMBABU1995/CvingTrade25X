CREATE OR REPLACE FUNCTION NORMALIZE_SYMBOL(p_symbol IN VARCHAR2)
RETURN VARCHAR2
DETERMINISTIC
AS
  v_value VARCHAR2(4000);
BEGIN
  v_value := UPPER(TRIM(NVL(p_symbol, '')));
  IF v_value LIKE 'NSE:%' THEN
    v_value := SUBSTR(v_value, 5);
  END IF;
  IF v_value LIKE '%-EQ' THEN
    v_value := SUBSTR(v_value, 1, LENGTH(v_value) - 3);
  END IF;
  v_value := REGEXP_REPLACE(v_value, '_\d{4}-\d{2}-\d{2}_\d{2}-\d{2}-\d{2}$', '');
  RETURN TRIM(v_value);
END;
