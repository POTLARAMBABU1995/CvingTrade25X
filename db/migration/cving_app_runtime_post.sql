DECLARE
  v_source_exists NUMBER := 0;
BEGIN
  SELECT COUNT(*) INTO v_source_exists
  FROM user_tables
  WHERE table_name = 'MV_NSE_SECTOR_UI_SNAPSHOT_SRC';

  IF v_source_exists > 0 THEN
    BEGIN
      EXECUTE IMMEDIATE 'DROP MATERIALIZED VIEW MV_NSE_SECTOR_UI_SNAPSHOT';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE NOT IN (-12003, -942) THEN
          NULL;
        END IF;
    END;

    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE MV_NSE_SECTOR_UI_SNAPSHOT';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
          NULL;
        END IF;
    END;

    EXECUTE IMMEDIATE q'[
      CREATE MATERIALIZED VIEW MV_NSE_SECTOR_UI_SNAPSHOT
      TABLESPACE CVING_DATA
      BUILD IMMEDIATE
      REFRESH COMPLETE ON DEMAND
      AS
      SELECT
        SYMBOL,
        SECTOR,
        INDEX_CODE,
        LTC_DATE,
        CLOSE_PRICE,
        RSI55_GT0,
        RSI50_GT0,
        SMA20,
        SMA50,
        SMA100
      FROM MV_NSE_SECTOR_UI_SNAPSHOT_SRC
    ]';
  END IF;
END;
