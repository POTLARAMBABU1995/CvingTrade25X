DECLARE
  v_exists NUMBER := 0;
  v_start_with NUMBER := 1;
BEGIN
  SELECT COUNT(*) INTO v_exists
  FROM user_tables
  WHERE table_name = 'ASURA_BULLISH_TREND_STRATEGY_TESTING';

  IF v_exists > 0 THEN
    EXECUTE IMMEDIATE 'SELECT NVL(MAX(S_NO), 0) + 1 FROM ASURA_BULLISH_TREND_STRATEGY_TESTING'
      INTO v_start_with;
  END IF;

  SELECT COUNT(*) INTO v_exists
  FROM user_sequences
  WHERE sequence_name = 'ASURA_BTS_SEQ';

  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE ASURA_BTS_SEQ START WITH ' || TO_CHAR(v_start_with) || ' INCREMENT BY 1 CACHE 50';
  END IF;
END;
