CREATE TABLE PIVOTS (
  PIVOT_ID          VARCHAR2(64)   NOT NULL,
  SYMBOL            VARCHAR2(32)   NOT NULL,
  TF                VARCHAR2(4)    NOT NULL,
  BAR_DATE          DATE           NOT NULL,
  PIVOT_TYPE        VARCHAR2(8)    NOT NULL,
  PRICE             NUMBER(18,6)   NOT NULL,
  LEFT_BARS         NUMBER(4)      NOT NULL,
  RIGHT_BARS        NUMBER(4)      NOT NULL,
  STRENGTH          NUMBER(10,4),
  CONFIDENCE        NUMBER(10,4),
  CREATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  UPDATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_PIVOTS PRIMARY KEY (PIVOT_ID)
);

CREATE TABLE SR_LEVELS (
  LEVEL_ID          VARCHAR2(64)   NOT NULL,
  SYMBOL            VARCHAR2(32)   NOT NULL,
  TF                VARCHAR2(4)    NOT NULL,
  LEVEL_TYPE        VARCHAR2(8)    DEFAULT 'SR' NOT NULL,
  SR_LEVEL          NUMBER(18,6)   NOT NULL,
  CREATED_AT        DATE           DEFAULT SYSDATE NOT NULL,
  UPDATED_AT        DATE           DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_SR_LEVELS PRIMARY KEY (LEVEL_ID)
);

CREATE TABLE PATTERNS (
  PATTERN_ID        VARCHAR2(64)   NOT NULL,
  SYMBOL            VARCHAR2(32)   NOT NULL,
  TF                VARCHAR2(4)    NOT NULL,
  PATTERN_TYPE      VARCHAR2(32)   NOT NULL,
  T1_DATE           DATE           NOT NULL,
  T2_DATE           DATE,
  BREAKOUT_DATE     DATE,
  PRICE_LOW         NUMBER(18,6),
  PRICE_HIGH        NUMBER(18,6),
  SCORE             NUMBER(10,4),
  CONFIDENCE        NUMBER(10,4),
  DETAILS_JSON      CLOB,
  CREATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  UPDATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_PATTERNS PRIMARY KEY (PATTERN_ID),
  CONSTRAINT CK_PATTERNS_JSON CHECK (DETAILS_JSON IS JSON OR DETAILS_JSON IS NULL)
);

CREATE TABLE ZONES (
  ZONE_ID           VARCHAR2(64)   NOT NULL,
  SYMBOL            VARCHAR2(32)   NOT NULL,
  TF                VARCHAR2(4)    NOT NULL,
  ZONE_TYPE         VARCHAR2(8)    NOT NULL,
  T1_DATE           DATE           NOT NULL,
