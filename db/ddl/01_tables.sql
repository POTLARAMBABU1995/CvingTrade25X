-- Core tables for charting module (Oracle 19c)

CREATE TABLE SYMBOLS (
  SYMBOL            VARCHAR2(32)   NOT NULL,
  NAME              VARCHAR2(128),
  EXCHANGE          VARCHAR2(16),
  SECTOR            VARCHAR2(64),
  IS_ACTIVE         CHAR(1)        DEFAULT 'Y' NOT NULL,
  FIRST_BAR_DATE    DATE,
  LAST_BAR_DATE     DATE,
  CREATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  UPDATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_SYMBOLS PRIMARY KEY (SYMBOL)
);

CREATE TABLE USERS (
  USER_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  EMAIL             VARCHAR2(128)  NOT NULL,
  DISPLAY_NAME      VARCHAR2(128),
  API_KEY           VARCHAR2(128),
  STATUS            VARCHAR2(16)   DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  UPDATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
  CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL)
);

