  PRICE_LOW         NUMBER(18,6)   NOT NULL,
  PRICE_HIGH        NUMBER(18,6)   NOT NULL,
  SCORE             NUMBER(10,4),
  CONFIDENCE        NUMBER(10,4),
  DETAILS_JSON      CLOB,
  CREATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  UPDATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_ZONES PRIMARY KEY (ZONE_ID),
  CONSTRAINT CK_ZONES_JSON CHECK (DETAILS_JSON IS JSON OR DETAILS_JSON IS NULL)
);

CREATE TABLE USER_ANNOTATIONS (
  ANNOTATION_ID     VARCHAR2(64)   NOT NULL,
  USER_ID           NUMBER         NOT NULL,
  SYMBOL            VARCHAR2(32)   NOT NULL,
  TF                VARCHAR2(4)    NOT NULL,
  PAYLOAD_JSON      CLOB           NOT NULL,
  CREATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  UPDATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_USER_ANNOTATIONS PRIMARY KEY (ANNOTATION_ID),
  CONSTRAINT FK_USER_ANNOTATIONS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
  CONSTRAINT CK_USER_ANNOTATIONS_JSON CHECK (PAYLOAD_JSON IS JSON)
);



