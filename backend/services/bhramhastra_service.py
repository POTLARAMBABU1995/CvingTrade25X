def _split_owner_and_table(name: str) -> Tuple[str, str]:
    raw = (name or "").strip()
    if "." in raw:
        owner, table = raw.rsplit(".", 1)
    else:
        owner, table = _BHRAMHASTRA_SCHEMA, raw
    return owner.strip('"').upper(), table.strip('"').upper()


def _id_is_identity(conn) -> bool:
    owner, table = _split_owner_and_table(BHRAMHASTRA_TABLE)
    with conn.cursor() as cur:
        try:
            cur.execute(
                """
                SELECT 1
                FROM USER_TAB_IDENTITY_COLS
                WHERE TABLE_NAME = :table_name
                  AND COLUMN_NAME = 'ID'
                """,
                {"table_name": table},
            )
            if cur.fetchone():
                return True
        except Exception:
            pass
        try:
            bind = {"table_name": table}
            sql = (
                """
                SELECT 1
                FROM ALL_TAB_IDENTITY_COLS
                WHERE TABLE_NAME = :table_name
                  AND COLUMN_NAME = 'ID'
                """
            )
            if owner:
                sql += " AND OWNER = :owner"
                bind["owner"] = owner
            cur.execute(sql, bind)
            return bool(cur.fetchone())
        except Exception:
            return False


def _assign_explicit_ids(conn, rows: List[Dict[str, Any]]) -> None:
    if not rows:
        return
    with conn.cursor() as cur:
        cur.execute(f"LOCK TABLE {BHRAMHASTRA_TABLE} IN EXCLUSIVE MODE")
        cur.execute(f"SELECT NVL(MAX(ID), 0) FROM {BHRAMHASTRA_TABLE}")
        row = cur.fetchone()
        base_id = int(row[0] or 0) if row else 0
    for offset, payload in enumerate(rows, start=1):
        payload["id"] = base_id + offset


@dataclass
class Candle:
    date: datetime
    open: float
    high: float
    low: float
    close: float
    volume: Optional[float]


def _normalize_timeframe(value: Optional[str]) -> str:
    if value is None or not str(value).strip():
        return "daily"
    tf = str(value).strip().lower()
    if tf not in VALID_TIMEFRAMES:
        raise ValueError("Invalid timeframe")
    return tf


def _min_required_candles(timeframe: str) -> int:
    baseline = max(EMA_PERIOD, RSI_PERIOD, ATR_PERIOD, MACD_SLOW)
    if timeframe == "yearly":
        baseline = max(baseline, 6)
    return baseline + 2


def _months_ago(base: date, months: int) -> date:
    year = base.year
    month = base.month - months
    while month <= 0:
        month += 12
        year -= 1
    day = min(base.day, calendar.monthrange(year, month)[1])
    return date(year, month, day)


def _cutoff_date_iso(months: int) -> Optional[str]:
    if months <= 0:
        return None
    cutoff = _months_ago(datetime.utcnow().date(), months)
    return cutoff.strftime("%Y-%m-%d")


def _cutoff_months_for_timeframe(timeframe: str) -> int:
    base = max(1, BHRAMHASTRA_CUTOFF_MONTHS)
    if timeframe == "monthly":
        return max(base, 48)
    if timeframe == "yearly":
        return max(base, 96)
    return base


def _periods_per_year(timeframe: str) -> int:
    return {
        "daily": 252,
        "weekly": 52,
        "monthly": 12,
        "yearly": 1,
    }.get(timeframe, 252)


def _aggregate_candles(candles: List[Candle], timeframe: str) -> List[Candle]:
    if timeframe == "daily":
        return candles

    buckets: Dict[Tuple[int, int], Dict[str, Any]] = {}
    for candle in candles:
        dt = candle.date
        if timeframe == "weekly":
            iso = dt.isocalendar()
            key = (iso[0], iso[1])
        elif timeframe == "monthly":
            key = (dt.year, dt.month)
        elif timeframe == "yearly":
            key = (dt.year, 0)
        else:
            return candles

        bucket = buckets.get(key)
        if bucket is None:
            volume_val = candle.volume if candle.volume is not None else None
            buckets[key] = {
                "date": dt,
                "open": candle.open,
                "high": candle.high,
                "low": candle.low,
                "close": candle.close,
                "volume": volume_val,
            }
            continue

        bucket["high"] = max(bucket["high"], candle.high)
        bucket["low"] = min(bucket["low"], candle.low)
        bucket["close"] = candle.close
        if bucket["open"] is None:
            bucket["open"] = candle.open
        if candle.volume is not None:
            bucket["volume"] = (bucket["volume"] or 0.0) + candle.volume
        bucket["date"] = dt

    aggregated: List[Candle] = []
    for bucket in sorted(buckets.values(), key=lambda b: b["date"]):
        aggregated.append(Candle(
            date=bucket["date"],
            open=bucket["open"],
            high=bucket["high"],
            low=bucket["low"],
            close=bucket["close"],
            volume=bucket["volume"],
        ))
    return aggregated


def _build_candles(entries: List[Dict[str, Any]]) -> List[Candle]:
    candles: List[Candle] = []
    for entry in entries:
        dt = entry.get("date")
        close_val = _safe_float(entry.get("close"))
        if not isinstance(dt, datetime) or close_val is None:
            continue
        open_val = _safe_float(entry.get("open")) or close_val
        high_val = _safe_float(entry.get("high")) or close_val
        low_val = _safe_float(entry.get("low")) or close_val
        volume_val = _safe_float(entry.get("volume"))
        candles.append(Candle(
            date=dt,
            open=open_val,
            high=high_val,
            low=low_val,
            close=close_val,
            volume=volume_val,
        ))
    candles.sort(key=lambda c: c.date)
    return candles


def _safe_float(value: Any) -> Optional[float]:
    if value is None:
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _safe_round(value: Optional[float], digits: int = 2) -> Optional[float]:
    if value is None:
        return None
    try:
        return round(float(value), digits)
    except (TypeError, ValueError):
        return None


def _source_series_stats(raw_series: Dict[str, List[Dict[str, Any]]]) -> Tuple[int, int, str]:
    row_count = 0
    latest = ""
    for entries in raw_series.values():
        if not isinstance(entries, list):
            continue
        row_count += len(entries)
        for entry in entries:
            value = entry.get("date") if isinstance(entry, dict) else None
            token = _fmt_iso(value) if isinstance(value, datetime) else ""
            if token and token > latest:
                latest = token
    return len(raw_series), row_count, latest


def _ema_series(values: List[float], period: int) -> List[Optional[float]]:
    if not values:
        return []
    k = 2 / (period + 1)
    out: List[Optional[float]] = []
    prev: Optional[float] = None
    for value in values:
        prev = value if prev is None else (value - prev) * k + prev
        out.append(prev)
    return out


def _compute_macd(closes: List[float]) -> Tuple[Optional[float], Optional[float], Optional[float]]:
    if len(closes) < MACD_SLOW + 1:
        return None, None, None
    ema_fast = _ema_series(closes, MACD_FAST)
    ema_slow = _ema_series(closes, MACD_SLOW)
    macd_line: List[float] = []
    for fast, slow in zip(ema_fast, ema_slow):
        if fast is None or slow is None:
            macd_line.append(0.0)
        else:
            macd_line.append(float(fast) - float(slow))
    signal_line = _ema_series(macd_line, MACD_SIGNAL)
    if not signal_line:
        return None, None, None
    return macd_line[-1], signal_line[-1], macd_line[-1] - (signal_line[-1] or 0.0)


def _compute_rsi_series(closes: List[float], period: int = RSI_PERIOD) -> List[Optional[float]]:
    if len(closes) < period + 1:
        return [None] * len(closes)
    rsi_values: List[Optional[float]] = [None] * len(closes)
    gains = []
    losses = []
    for i in range(1, period + 1):
        delta = closes[i] - closes[i - 1]
        gains.append(max(delta, 0.0))
        losses.append(max(-delta, 0.0))
    avg_gain = sum(gains) / period
    avg_loss = sum(losses) / period
    rs = (avg_gain / avg_loss) if avg_loss > 0 else None
    rsi_values[period] = 100.0 if rs is None else 100 - (100 / (1 + rs))
    for idx in range(period + 1, len(closes)):
        delta = closes[idx] - closes[idx - 1]
        gain = max(delta, 0.0)
        loss = max(-delta, 0.0)
        avg_gain = ((avg_gain * (period - 1)) + gain) / period
        avg_loss = ((avg_loss * (period - 1)) + loss) / period
        if avg_loss == 0:
            rsi_values[idx] = 100.0
        else:
            rs = avg_gain / avg_loss
            rsi_values[idx] = 100 - (100 / (1 + rs))
    return rsi_values


def _true_ranges(candles: List[Candle]) -> List[float]:
    ranges: List[float] = []
    prev_close: Optional[float] = None
    for candle in candles:
        high = candle.high
        low = candle.low
        close = candle.close
        if prev_close is None:
            tr = high - low
        else:
            tr = max(high - low, abs(high - prev_close), abs(low - prev_close))
        ranges.append(tr)
        prev_close = close
    return ranges


def _wilder_atr(trs: List[float], period: int) -> List[Optional[float]]:
    length = len(trs)
    if length < period:
        return [None] * length
    atrs: List[Optional[float]] = [None] * length
    first_avg = sum(trs[:period]) / period
    atrs[period - 1] = first_avg
    for idx in range(period, length):
        prev_atr = atrs[idx - 1]
        if prev_atr is None:
            prev_atr = first_avg
        atrs[idx] = ((prev_atr * (period - 1)) + trs[idx]) / period
    return atrs


def _compute_adx_last(candles: List[Candle], period: int = 14) -> Optional[float]:
    if len(candles) < period + 1:
        return None

    tr_list: List[float] = []
    plus_dm_list: List[float] = []
    minus_dm_list: List[float] = []

    for idx in range(1, len(candles)):
        current = candles[idx]
        previous = candles[idx - 1]
        up_move = current.high - previous.high
        down_move = previous.low - current.low
        plus_dm = up_move if up_move > down_move and up_move > 0 else 0.0
        minus_dm = down_move if down_move > up_move and down_move > 0 else 0.0
        true_range = max(
            current.high - current.low,
            abs(current.high - previous.close),
            abs(current.low - previous.close),
        )
        tr_list.append(true_range)
        plus_dm_list.append(plus_dm)
        minus_dm_list.append(minus_dm)

    if len(tr_list) < period:
        return None

    tr_sum = sum(tr_list[:period])
    plus_dm_sum = sum(plus_dm_list[:period])
    minus_dm_sum = sum(minus_dm_list[:period])

    def _di(dm_value: float, tr_value: float) -> float:
        return 100.0 * dm_value / tr_value if tr_value else 0.0

    plus_di = _di(plus_dm_sum, tr_sum)
    minus_di = _di(minus_dm_sum, tr_sum)
    denom = plus_di + minus_di
    dx_list: List[float] = [100.0 * abs(plus_di - minus_di) / denom if denom else 0.0]

    for idx in range(period, len(tr_list)):
        tr_sum = tr_sum - (tr_sum / period) + tr_list[idx]
        plus_dm_sum = plus_dm_sum - (plus_dm_sum / period) + plus_dm_list[idx]
        minus_dm_sum = minus_dm_sum - (minus_dm_sum / period) + minus_dm_list[idx]
        plus_di = _di(plus_dm_sum, tr_sum)
        minus_di = _di(minus_dm_sum, tr_sum)
        denom = plus_di + minus_di
        dx_list.append(100.0 * abs(plus_di - minus_di) / denom if denom else 0.0)

    if len(dx_list) < period:
        return None

    adx = sum(dx_list[:period]) / period
    for dx in dx_list[period:]:
        adx = ((adx * (period - 1)) + dx) / period
    return adx


def _apply_trend_display_fields(row: Dict[str, Any]) -> None:
    try:
        trend_result = calculate_master_trend(row)
    except Exception:
        _logger.exception("bhramhastra_trend_display_failed symbol=%s", row.get("symbol"))
        return
    trend = str(trend_result.get("trend") or "").strip()
    if not trend:
        return
    row["trend"] = trend
    row["trendDirection"] = trend
    row["trendSort"] = trend_result.get("trendSort")
    row["trendDirectionSort"] = trend_result.get("trendSort")
    row["trendDecisionReason"] = trend_result.get("trendDecisionReason")
    row["trendSource"] = trend_result.get("trendSource")


def _first_present(row: Dict[str, Any], *keys: str) -> Any:
    for key in keys:
        value = row.get(key)
        if value is None:
            continue
        if isinstance(value, str) and not value.strip():
            continue
        return value
    return None


def _missing_display_value(row: Dict[str, Any], key: str) -> bool:
    value = row.get(key)
    return value is None or (isinstance(value, str) and not value.strip())


def _set_if_missing(row: Dict[str, Any], key: str, value: Any) -> bool:
    if value is None or not _missing_display_value(row, key):
        return False
    row[key] = value
    return True


def _gap_pct(price: Any, ath: Any) -> Optional[float]:
    price_num = _safe_float(price)
    ath_num = _safe_float(ath)
    if price_num is None or ath_num is None or ath_num == 0:
        return None
    return ((price_num - ath_num) / ath_num) * 100.0


def _repair_row_display_fields(row: Dict[str, Any], candles: List[Candle]) -> bool:
    changed = False

    price = _safe_float(_first_present(row, "priceSort", "price", "entryPrice", "close", "PRICE"))
    if price is None and candles:
        price = candles[-1].close
    if price is not None:
        changed = _set_if_missing(row, "price", _safe_round(price, 2)) or changed
        changed = _set_if_missing(row, "priceSort", price) or changed

    ath = _safe_float(_first_present(row, "ath", "ATH"))
    if ath is None and candles:
        ath = _calc_ath(candles)

    gap = _gap_pct(price, ath)
    if gap is not None:
        changed = _set_if_missing(row, "gap", _safe_round(gap, 2)) or changed
        changed = _set_if_missing(row, "gapSort", gap) or changed
        changed = _set_if_missing(row, "GAP", _safe_round(gap, 2)) or changed
        changed = _set_if_missing(row, "GAP_SORT", gap) or changed

    changed = _set_if_missing(row, "setupType", BHRAMHASTRA_SETUP_TYPE) or changed
    changed = _set_if_missing(row, "setup_type", BHRAMHASTRA_SETUP_TYPE) or changed

    if not candles:
        return changed

    closes = [c.close for c in candles]
    ema20_series = _ema_series(closes, 20)
    ema50_series = _ema_series(closes, EMA_PERIOD)
    ema100_series = _ema_series(closes, 100)
    ema200_series = _ema_series(closes, 200)
    ema20 = ema20_series[-1] if ema20_series else None
    ema50 = ema50_series[-1] if ema50_series else None
    ema100 = ema100_series[-1] if ema100_series else None
    ema200 = ema200_series[-1] if ema200_series else None
    adx_now = _compute_adx_last(candles, 14)

    changed = _set_if_missing(row, "ema20", _safe_round(ema20, 2)) or changed
    changed = _set_if_missing(row, "ema20Sort", ema20) or changed
    changed = _set_if_missing(row, "ema50", _safe_round(ema50, 2)) or changed
    changed = _set_if_missing(row, "ema50Sort", ema50) or changed
    changed = _set_if_missing(row, "ema100", _safe_round(ema100, 2)) or changed
    changed = _set_if_missing(row, "ema100Sort", ema100) or changed
    changed = _set_if_missing(row, "ema200", _safe_round(ema200, 2)) or changed
    changed = _set_if_missing(row, "ema200Sort", ema200) or changed
    changed = _set_if_missing(row, "adx14", _safe_round(adx_now, 2)) or changed
    changed = _set_if_missing(row, "adx14Sort", adx_now) or changed

    if _missing_display_value(row, "trendDirection"):
        before = row.get("trendDirection")
        _apply_trend_display_fields(row)
        changed = changed or row.get("trendDirection") != before

    return changed


def repair_bhramhastra_display_fields(payload: Dict[str, Any] | None, timeframe: Optional[str] = None) -> Tuple[Dict[str, Any], int]:
    """Backfill display-only fields on existing rows without changing strategy membership."""
    if not isinstance(payload, dict):
        return {}, 0
    rows = payload.get("rows")
    if not isinstance(rows, list) or not rows:
        return payload, 0

    tf = _normalize_timeframe(timeframe or str(payload.get("timeframe") or "daily"))
    row_items = [row for row in rows if isinstance(row, dict)]
    repaired_row_ids: set[int] = set()
    for row in row_items:
        changed = _set_if_missing(row, "setupType", BHRAMHASTRA_SETUP_TYPE)
        changed = _set_if_missing(row, "setup_type", BHRAMHASTRA_SETUP_TYPE) or changed
        if changed:
            repaired_row_ids.add(id(row))

    needs_repair = [
        row for row in row_items
        if any(_missing_display_value(row, key) for key in ("ema20", "ema100", "ema200", "adx14", "trendDirection", "gap"))
    ]
    if not needs_repair:
        repaired = len(repaired_row_ids)
        if repaired:
            payload["displayFieldsRepairedAt"] = datetime.utcnow().isoformat() + "Z"
            payload["displayFieldsSource"] = "NSE_NIFTY500_DAILY_RAW_DATA_DEV"
        return payload, repaired

    raw_series = fetch_ohlc_series_from_oracle(months=_cutoff_months_for_timeframe(tf))
    series_by_symbol = {str(symbol).strip().upper(): entries for symbol, entries in raw_series.items()}

    for row in needs_repair:
        symbol = str(_first_present(row, "symbol", "stockName", "stock", "SYMBOL") or "").strip().upper()
        entries = series_by_symbol.get(symbol) or []
        candles = _aggregate_candles(_build_candles(entries), tf)
        if _repair_row_display_fields(row, candles):
            repaired_row_ids.add(id(row))

    repaired = len(repaired_row_ids)
    if not repaired:
        return payload, 0

    payload["displayFieldsRepairedAt"] = datetime.utcnow().isoformat() + "Z"
    payload["displayFieldsSource"] = "NSE_NIFTY500_DAILY_RAW_DATA_DEV"
    return payload, repaired


def _avg_volume(candles: List[Candle]) -> Optional[float]:
    volumes = [c.volume for c in candles if c.volume is not None and c.volume > 0]
    if not volumes:
        return None
    window = volumes[-VOL_WINDOW:] if len(volumes) >= VOL_WINDOW else volumes
    return fmean(window) if window else None


def _calc_high_low(candles: List[Candle], window: int) -> Tuple[Optional[float], Optional[float]]:
    if not candles:
        return None, None
    subset = candles[-window:] if len(candles) >= window else candles
    highs = [c.high for c in subset if c.high is not None]
    lows = [c.low for c in subset if c.low is not None]
    return (max(highs) if highs else None, min(lows) if lows else None)


def _calc_ath(candles: List[Candle]) -> Optional[float]:
    highs = [c.high for c in candles if c.high is not None]
    return max(highs) if highs else None


def _support_resistance(candles: List[Candle], window: int = 20) -> Tuple[Optional[float], Optional[float]]:
    if not candles:
        return None, None
    subset = candles[-window:] if len(candles) >= window else candles
    lows = [c.low for c in subset if c.low is not None]
    highs = [c.high for c in subset if c.high is not None]
    support = min(lows) if lows else None
    resistance = max(highs) if highs else None
    return support, resistance


def _fmt_iso(value: Optional[datetime]) -> Optional[str]:
    if isinstance(value, datetime):
        return value.strftime("%Y-%m-%d")
    return None


def _compute_targets(price: float, atr_value: Optional[float]) -> Tuple[float, float, float, float]:
    atr_risk = (atr_value or 0.0) * BHRAMHASTRA_STOP_ATR_MULT
    risk = max((price * BHRAMHASTRA_STOP_PCT) + atr_risk, price * 0.0025)
    target1 = price + (risk * BHRAMHASTRA_TARGET1_RR)
    target2 = price + (risk * BHRAMHASTRA_TARGET2_RR)
    stop_loss = price - risk
    return target1, target2, stop_loss, risk


