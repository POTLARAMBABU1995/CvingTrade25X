def _fetch_existing_signal_keys(conn, rows: List[Dict[str, Any]]) -> set[Tuple[str, date]]:
    ltc_dates = sorted({
        parsed
        for parsed in (_parse_row_date(row.get("ltcDate") or row.get("tradeDate")) for row in rows)
        if parsed is not None
    })
    if not ltc_dates:
        return set()
    binds = {f"ltc_date_{idx}": value for idx, value in enumerate(ltc_dates)}
    placeholders = ", ".join(f":ltc_date_{idx}" for idx in range(len(ltc_dates)))
    with conn.cursor() as cur:
        cur.execute(
            f"""
            SELECT SYMBOL, LTC_DATE
            FROM {BHRAMHASTRA_TABLE}
            WHERE LTC_DATE IN ({placeholders})
            """,
            binds,
        )
        existing: set[Tuple[str, date]] = set()
        for symbol, ltc_date in cur.fetchall() or []:
            parsed_date = _parse_row_date(ltc_date)
            normalized_symbol = str(symbol or "").strip().upper()
            if normalized_symbol and parsed_date:
                existing.add((normalized_symbol, parsed_date))
        return existing


def _fetch_symbol_backtest_anchor(conn, symbols: List[str]) -> Dict[str, date]:
    normalized = sorted({str(symbol or "").strip().upper() for symbol in symbols if str(symbol or "").strip()})
    if not normalized:
        return {}
    binds = {f"symbol_{idx}": value for idx, value in enumerate(normalized)}
    placeholders = ", ".join(f":symbol_{idx}" for idx in range(len(normalized)))
    with conn.cursor() as cur:
        cur.execute(
            f"""
            SELECT SYMBOL, MIN(BACKTEST_DATE) AS BACKTEST_DATE
            FROM {BHRAMHASTRA_TABLE}
            WHERE SYMBOL IN ({placeholders})
              AND BACKTEST_DATE IS NOT NULL
            GROUP BY SYMBOL
            """,
            binds,
        )
        anchors: Dict[str, date] = {}
        for symbol, backtest_date in cur.fetchall() or []:
            parsed = _parse_row_date(backtest_date)
            normalized_symbol = str(symbol or "").strip().upper()
            if normalized_symbol and parsed:
                anchors[normalized_symbol] = parsed
        return anchors


def _exit_signal(latest: Dict[str, Any], row: Dict[str, Any]) -> Tuple[Optional[str], Optional[float]]:
    try:
        high = float(latest.get("high") or 0)
        low = float(latest.get("low") or 0)
        target1 = float(row.get("target1") or 0)
        target2 = float(row.get("target2") or 0)
        stop_loss = float(row.get("stopLoss") or 0)
    except (TypeError, ValueError):
        return None, None
    if target2 and high >= target2:
        return "TARGET2", target2
    if target1 and high >= target1:
        return "TARGET1", target1
    if stop_loss and low <= stop_loss:
        return "STOP_LOSS", stop_loss
    return None, None



