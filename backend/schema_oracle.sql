-- Oracle schema for CvingTrade25X users/auth/session features

CREATE TABLE USERS (
    USER_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME         VARCHAR2(100),
    EMAIL             VARCHAR2(150) UNIQUE NOT NULL,
    MOBILE_NUMBER     VARCHAR2(15) UNIQUE NOT NULL,
    CLIENT_ID         VARCHAR2(50) UNIQUE NOT NULL,
    PASSWORD_HASH     VARCHAR2(256),
    MPIN              VARCHAR2(10),
    LOGIN_METHOD      VARCHAR2(50),
    CREATED_AT        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT        TIMESTAMP
);

CREATE TABLE USER_LOGIN_ACTIVITY (
    ACTIVITY_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID        NUMBER REFERENCES USERS(USER_ID),
    LOGIN_TIME     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    LOGIN_IP       VARCHAR2(50),
    LOGIN_DEVICE   VARCHAR2(100),
    LOCATION       VARCHAR2(100),
    METHOD_USED    VARCHAR2(50)
);

CREATE TABLE USER_SETTINGS (
    USER_ID         NUMBER PRIMARY KEY REFERENCES USERS(USER_ID),
    DARK_MODE       CHAR(1) DEFAULT 'N',
    LANGUAGE        VARCHAR2(20) DEFAULT 'EN',
    NOTIFICATIONS   CHAR(1) DEFAULT 'Y'
);

CREATE TABLE ANNOUNCEMENTS (
    ANNOUNCEMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE           VARCHAR2(200),
    MESSAGE         VARCHAR2(1000),
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    EXPIRY_DATE     DATE
);

CREATE TABLE WATCHLIST (
    WATCHLIST_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER REFERENCES USERS(USER_ID),
    SYMBOL          VARCHAR2(50),
    ADDED_AT        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

