-- Oracle 19c table for Bhramhastra backtest storage.
-- Stores each signal (EMA50/RSI/MACD/VOLUME condition met) and tracks exit outcomes.

CREATE TABLE BHRAMHASTRA_BACKTEST (
  ID               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  SYMBOL           VARCHAR2(30) NOT NULL,
  STOCK_NAME       VARCHAR2(200),
  TRADE_DATE       DATE NOT NULL,
  ENTRY_PRICE      NUMBER(12,4),
  EMA50            NUMBER(12,4),
  RSI14            NUMBER(6,2),
  MACD_HIST        NUMBER(12,6),
  VOLUME           NUMBER(20,2),
  ATR14            NUMBER(12,4),
  HIGH_52W         NUMBER(12,4),
  LOW_52W          NUMBER(12,4),
  ATH              NUMBER(12,4),
  HIGH_1Y          NUMBER(12,4),
  HIGH_2Y          NUMBER(12,4),
  SUPPORT_PRICE    NUMBER(12,4),
  RESISTANCE_PRICE NUMBER(12,4),
  TARGET1          NUMBER(12,4),
  TARGET2          NUMBER(12,4),
  STOP_LOSS        NUMBER(12,4),
  BACKTEST_DATE    DATE,
  EXIT_DATE        DATE,
  EXIT_PRICE       NUMBER(12,4),
  EXIT_REASON      VARCHAR2(20),
  STATUS           VARCHAR2(10) DEFAULT 'OPEN',
  CREATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT       TIMESTAMP
);

CREATE UNIQUE INDEX BHRAMHASTRA_BACKTEST_UK ON BHRAMHASTRA_BACKTEST (SYMBOL, TRADE_DATE);
CREATE INDEX BHRAMHASTRA_BACKTEST_STATUS_IDX ON BHRAMHASTRA_BACKTEST (STATUS);
CREATE INDEX BHRAMHASTRA_BACKTEST_DATE_IDX ON BHRAMHASTRA_BACKTEST (TRADE_DATE);
