    LTC_DATE DATE,
    REFRESH_STATUS VARCHAR2(50),
    ROW_COUNT NUMBER,
    DURATION_MS NUMBER,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
