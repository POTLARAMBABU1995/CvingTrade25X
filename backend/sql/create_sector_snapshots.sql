CREATE TABLE NSE_SECTOR_ROTATION_SNAPSHOT (
    LTC_DATE DATE NOT NULL,
    SECTOR VARCHAR2(100) NOT NULL,
    RSI55 NUMBER,
    RSI50 NUMBER,
    SMA20 NUMBER,
    SMA50 NUMBER,
    SMA100 NUMBER,
    SCORE NUMBER,
    PAYLOAD_JSON CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    REFRESH_STATUS VARCHAR2(50),
    ROW_COUNT NUMBER,
    SOURCE_MAX_TRADING_DATE DATE,
    CONSTRAINT PK_NSE_SECTOR_ROT_SNAP PRIMARY KEY (LTC_DATE, SECTOR),
    CONSTRAINT CHK_NSE_SECTOR_ROT_SNAP_JSON CHECK (PAYLOAD_JSON IS JSON)
);

CREATE INDEX IDX_NSE_SECTOR_ROT_SNAP_LTC ON NSE_SECTOR_ROTATION_SNAPSHOT(LTC_DATE);
CREATE INDEX IDX_NSE_SECTOR_ROT_SNAP_SEC_LTC ON NSE_SECTOR_ROTATION_SNAPSHOT(SECTOR, LTC_DATE);

CREATE TABLE NSE_SECTOR_WISE_STOCKS_SNAPSHOT (
    LTC_DATE DATE NOT NULL,
    SECTOR VARCHAR2(100) NOT NULL,
    SYMBOL VARCHAR2(100) NOT NULL,
    IDX_CODE VARCHAR2(100),
    MCAP NUMBER,
    MCAP_RANK NUMBER,
    PRICE NUMBER,
    ATH NUMBER,
    GAP NUMBER,
    WH52 NUMBER,
    WL52 NUMBER,
    EMA20_FLAG VARCHAR2(50),
    EMA50_FLAG VARCHAR2(50),
    EMA100_FLAG VARCHAR2(50),
    EMA200_FLAG VARCHAR2(50),
    TREND VARCHAR2(50),
    SCORE NUMBER,
    PAYLOAD_JSON CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_NSE_SEC_STOCKS_SNAP PRIMARY KEY (LTC_DATE, SECTOR, SYMBOL),
    CONSTRAINT CHK_NSE_SEC_STOCKS_SNAP_JSON CHECK (PAYLOAD_JSON IS JSON)
);

CREATE INDEX IDX_NSE_SEC_STOCKS_SNAP_SEC ON NSE_SECTOR_WISE_STOCKS_SNAPSHOT(SECTOR, LTC_DATE);
CREATE INDEX IDX_NSE_SEC_STOCKS_SNAP_SYM ON NSE_SECTOR_WISE_STOCKS_SNAPSHOT(SYMBOL, LTC_DATE);
CREATE INDEX IDX_NSE_SEC_STOCKS_SNAP_RNK ON NSE_SECTOR_WISE_STOCKS_SNAPSHOT(LTC_DATE, MCAP_RANK);

CREATE TABLE NSE_SECTOR_CACHE_AUDIT_LOG (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
