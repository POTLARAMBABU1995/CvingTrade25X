DECLARE
  v_exists NUMBER := 0;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM USER_TABLES WHERE TABLE_NAME = 'CVING_NSE_DELIVERY_HIST';
  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE CVING_NSE_DELIVERY_HIST (
        ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        TRADE_DATE DATE NOT NULL,
        SYMBOL VARCHAR2(50) NOT NULL,
        SOURCE_NAME VARCHAR2(50) NOT NULL,
        SERIES VARCHAR2(10),
        SECURITY_NAME VARCHAR2(300),
        PREV_CLOSE NUMBER(24,6),
        CLOSE_PRICE NUMBER(24,6),
        TOTAL_TRADED_QTY NUMBER(24,6),
        TURNOVER_LACS NUMBER(24,6),
        NO_OF_TRADES NUMBER(24,6),
        DELIVERY_QTY NUMBER(24,6),
        DELIVERY_PCT NUMBER(12,6),
        RESPONSE_PAYLOAD CLOB,
        FETCH_STATUS VARCHAR2(30) DEFAULT 'SUCCESS' NOT NULL,
        ERROR_MESSAGE VARCHAR2(2000),
        FETCH_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CREATED_BY VARCHAR2(128) DEFAULT USER NOT NULL,
        UPDATED_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT UQ_CVING_NSE_DELIVERY UNIQUE (TRADE_DATE, SYMBOL, SOURCE_NAME),
        CONSTRAINT CK_CVING_NSE_DELIVERY_STATUS CHECK (FETCH_STATUS IN ('SUCCESS', 'FAILED', 'PARTIAL', 'SKIPPED', 'PARSE_ERROR')),
        CONSTRAINT CK_CVING_NSE_DELIVERY_JSON CHECK (RESPONSE_PAYLOAD IS JSON OR RESPONSE_PAYLOAD IS NULL)
      )
    ]';
  END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IDX_CVING_NSE_DELIVERY_TRDDATE ON CVING_NSE_DELIVERY_HIST (TRADE_DATE, FETCH_STATUS)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IDX_CVING_NSE_DELIVERY_SYMDATE ON CVING_NSE_DELIVERY_HIST (SYMBOL, TRADE_DATE DESC)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

CREATE OR REPLACE VIEW VW_CVING_NSE_DELIVERY_LATEST AS
SELECT id, trade_date, symbol, source_name, series, security_name,
       prev_close, close_price, total_traded_qty, turnover_lacs,
       no_of_trades, delivery_qty, delivery_pct, response_payload,
       fetch_status, error_message, fetch_ts, created_by, updated_ts
FROM (
  SELECT t.*, ROW_NUMBER() OVER (
    PARTITION BY t.symbol, t.source_name
    ORDER BY t.trade_date DESC, t.fetch_ts DESC, t.updated_ts DESC
  ) rn
  FROM CVING_NSE_DELIVERY_HIST t
)
WHERE rn = 1;

