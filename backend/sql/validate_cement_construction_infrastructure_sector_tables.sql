PROMPT [5] Cross-sector duplicate symbol check (across ALL staging tables)
WITH all_stage_symbols AS (
    SELECT symbol, 'NSE_NIFTY_CEMENT_CEMENT_PRODUCTS_STAGING' AS src FROM NSE_NIFTY_CEMENT_CEMENT_PRODUCTS_STAGING
    UNION ALL
    SELECT symbol, 'NSE_NIFTY_CONSTRUCTION_STAGING' FROM NSE_NIFTY_CONSTRUCTION_STAGING
    UNION ALL
    SELECT symbol, 'NSE_NIFTY_CONSTRUCTION_MATERIALS_STAGING' FROM NSE_NIFTY_CONSTRUCTION_MATERIALS_STAGING
    UNION ALL
    SELECT symbol, 'NSE_NIFTY_INFRASTRUCTURE_STAGING' FROM NSE_NIFTY_INFRASTRUCTURE_STAGING
    UNION ALL
    -- Include other staging tables dynamically or select from them
    SELECT map.symbol, 'NSE_SYMBOL_SECTOR_MAP/' || map.sector_code
    FROM nse_symbol_sector_map map
    WHERE map.sector_code NOT IN ('CEMENT_CEMENT_PRODUCTS', 'CONSTRUCTION', 'CONSTRUCTION_MATERIALS', 'INFRASTRUCTURE')
)
SELECT symbol, COUNT(DISTINCT src) AS matches, MIN(src) AS first_src, MAX(src) AS second_src
FROM all_stage_symbols
GROUP BY symbol
HAVING COUNT(DISTINCT src) > 1
ORDER BY symbol;

