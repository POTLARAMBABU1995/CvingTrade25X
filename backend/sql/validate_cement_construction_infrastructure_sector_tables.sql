PROMPT Validating Cement, Construction and Infrastructure sector tables
SET DEFINE OFF;

PROMPT [1] Staging tables presence
SELECT table_name FROM user_tables 
WHERE table_name IN (
    'NSE_NIFTY_CEMENT_CEMENT_PRODUCTS_STAGING',
    'NSE_NIFTY_CONSTRUCTION_STAGING',
    'NSE_NIFTY_CONSTRUCTION_MATERIALS_STAGING',
    'NSE_NIFTY_INFRASTRUCTURE_STAGING'
)
ORDER BY table_name;

