PROMPT [8] DEV table to Staging table joins (Sample rows returning OHLCV)
SELECT 'CEMENT' AS sec, COUNT(DISTINCT dev.symbol) AS active_dev_symbols, COUNT(*) AS raw_ohlcv_rows
FROM NSE_NIFTY_CEMENT_CEMENT_PRODUCTS_STAGING stg
JOIN NSE_NIFTY500_DAILY_RAW_DATA_DEV dev ON dev.symbol = stg.symbol
UNION ALL
SELECT 'CONSTRUCTION', COUNT(DISTINCT dev.symbol), COUNT(*)
FROM NSE_NIFTY_CONSTRUCTION_STAGING stg
JOIN NSE_NIFTY500_DAILY_RAW_DATA_DEV dev ON dev.symbol = stg.symbol
UNION ALL
SELECT 'CONSTRUCTION_MATERIALS', COUNT(DISTINCT dev.symbol), COUNT(*)
FROM NSE_NIFTY_CONSTRUCTION_MATERIALS_STAGING stg
JOIN NSE_NIFTY500_DAILY_RAW_DATA_DEV dev ON dev.symbol = stg.symbol
UNION ALL
SELECT 'INFRASTRUCTURE', COUNT(DISTINCT dev.symbol), COUNT(*)
FROM NSE_NIFTY_INFRASTRUCTURE_STAGING stg
JOIN NSE_NIFTY500_DAILY_RAW_DATA_DEV dev ON dev.symbol = stg.symbol;
