-- Forward DDL for Bhramhastra backtesting storage.
-- Oracle will store the object name in uppercase unless quoted.

CREATE TABLE Bhramhastra_BackTesting_Data (
  ID               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  S_NO             NUMBER,
  SYMBOL           VARCHAR2(30) NOT NULL,
  STOCK_NAME       VARCHAR2(200),
  LTC_DATE         DATE NOT NULL,
  TRADE_DATE       DATE,
  FIRST_TRADE_DATE DATE,
  CALENDAR_DAYS    NUMBER,
  TRADING_DAYS     NUMBER,
  ENTRY_PRICE      NUMBER(18,4),
  EMA50            NUMBER(18,4),
  RSI14            NUMBER(10,4),
  MACD_HIST        NUMBER(18,6),
  VOLUME           NUMBER(20,2),
  ATR14            NUMBER(18,4),
  RISK_AMOUNT      NUMBER(18,4),
  TARGET1          NUMBER(18,4),
  TARGET2          NUMBER(18,4),
  TARGET1_RRR      NUMBER(10,4) DEFAULT 2,
  TARGET2_RRR      NUMBER(10,4) DEFAULT 3,
  STOP_LOSS        NUMBER(18,4),
  BACKTEST_DATE    DATE,
  HIGH_52W         NUMBER(18,4),
  LOW_52W          NUMBER(18,4),
  ATH              NUMBER(18,4),
  HIGH_1Y          NUMBER(18,4),
  HIGH_2Y          NUMBER(18,4),
  SUPPORT_PRICE    NUMBER(18,4),
  RESISTANCE_PRICE NUMBER(18,4),
  EXIT_DATE        DATE,
  EXIT_PRICE       NUMBER(18,4),
  EXIT_REASON      VARCHAR2(30),
  STATUS           VARCHAR2(20) DEFAULT 'OPEN',
  CREATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT UK_BHRAMHASTRA_BT_SIGNAL UNIQUE (SYMBOL, LTC_DATE)
);

CREATE INDEX IDX_BHRAMHASTRA_BT_LTC_DATE ON Bhramhastra_BackTesting_Data (LTC_DATE);
CREATE INDEX IDX_BHRAMHASTRA_BT_STATUS ON Bhramhastra_BackTesting_Data (STATUS);
