-- FYERS holdings storage for automated CSV imports and current-position CRUD.
-- Run this in the target Oracle schema.

CREATE TABLE FYERS_HOLDINGS_IMPORTS (
    IMPORT_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REPORT_TITLE         VARCHAR2(200),
    REPORT_DATE          DATE,
    CLIENT_NAME          VARCHAR2(150),
    CLIENT_ID            VARCHAR2(50) NOT NULL,
    PAN                  VARCHAR2(20),
    DOWNLOAD_TIMESTAMP   TIMESTAMP,
    TOTAL_INVESTED       NUMBER(20, 4),
    TOTAL_CURRENT        NUMBER(20, 4),
    PROFIT_LOSS          NUMBER(20, 4),
    UNREALISED_PNL_PCT   NUMBER(12, 4),
    SOURCE_FILENAME      VARCHAR2(260),
    SOURCE_PATH          VARCHAR2(1000),
    SOURCE_HASH          VARCHAR2(128),
    IMPORT_MODE          VARCHAR2(30) DEFAULT 'UPLOAD' NOT NULL,
    STATUS               VARCHAR2(30) DEFAULT 'COMPLETED' NOT NULL,
    ROW_COUNT            NUMBER DEFAULT 0 NOT NULL,
    INSERTED_COUNT       NUMBER DEFAULT 0 NOT NULL,
    UPDATED_COUNT        NUMBER DEFAULT 0 NOT NULL,
    DELETED_COUNT        NUMBER DEFAULT 0 NOT NULL,
    UNCHANGED_COUNT      NUMBER DEFAULT 0 NOT NULL,
    ERROR_COUNT          NUMBER DEFAULT 0 NOT NULL,
    MESSAGE              VARCHAR2(1000),
    REPLACE_MISSING      CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_AT         TIMESTAMP,
    CONSTRAINT FYERS_HOLDINGS_IMPORTS_RM_CHK CHECK (REPLACE_MISSING IN ('Y', 'N'))
);

CREATE TABLE FYERS_HOLDINGS_CURRENT (
    HOLDING_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IMPORT_ID            NUMBER,
    CLIENT_ID            VARCHAR2(50) NOT NULL,
    CLIENT_NAME          VARCHAR2(150),
    PAN                  VARCHAR2(20),
    REPORT_DATE          DATE,
    DOWNLOAD_TIMESTAMP   TIMESTAMP,
    SYMBOL_RAW           VARCHAR2(80) NOT NULL,
    EXCHANGE_CODE        VARCHAR2(20),
    SYMBOL_CODE          VARCHAR2(50) NOT NULL,
    SERIES_CODE          VARCHAR2(20),
    QUANTITY             NUMBER(20, 4),
    BUY_PRICE            NUMBER(20, 4),
    INVESTED_VALUE       NUMBER(20, 4),
    CURRENT_VALUE        NUMBER(20, 4),
    UNREALISED_PNL       NUMBER(20, 4),
    UNREALISED_PNL_PCT   NUMBER(12, 4),
    PREVIOUS_CLOSE       NUMBER(20, 4),
    ISIN                 VARCHAR2(30),
    SOURCE_FILENAME      VARCHAR2(260),
    SOURCE_PATH          VARCHAR2(1000),
    SOURCE_HASH          VARCHAR2(128),
    CREATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FYERS_HOLDINGS_CURR_IMP_FK FOREIGN KEY (IMPORT_ID)
        REFERENCES FYERS_HOLDINGS_IMPORTS (IMPORT_ID)
);

CREATE UNIQUE INDEX FYERS_HOLDINGS_CURR_UK1
    ON FYERS_HOLDINGS_CURRENT (CLIENT_ID, SYMBOL_CODE);

CREATE INDEX FYERS_HOLDINGS_CURR_IDX1
    ON FYERS_HOLDINGS_CURRENT (CLIENT_ID, REPORT_DATE, UPDATED_AT);

CREATE TABLE FYERS_HOLDINGS_AUDIT (
    AUDIT_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    HOLDING_ID           NUMBER,
    IMPORT_ID            NUMBER,
    CLIENT_ID            VARCHAR2(50) NOT NULL,
    SYMBOL_CODE          VARCHAR2(50) NOT NULL,
    ACTION_TYPE          VARCHAR2(20) NOT NULL,
    ACTION_SOURCE        VARCHAR2(20) NOT NULL,
    BEFORE_STATE         CLOB,
    AFTER_STATE          CLOB,
    CHANGED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FYERS_HOLDINGS_AUDIT_IMP_FK FOREIGN KEY (IMPORT_ID)
        REFERENCES FYERS_HOLDINGS_IMPORTS (IMPORT_ID)
);

CREATE INDEX FYERS_HOLDINGS_AUDIT_IDX1
    ON FYERS_HOLDINGS_AUDIT (CLIENT_ID, SYMBOL_CODE, CHANGED_AT);
