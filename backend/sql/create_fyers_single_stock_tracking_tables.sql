-- FYERS single-stock tracking tables
-- Purpose:
-- 1) FYERS_REUSE_SYMBOLS stores failed/skipped symbols for reprocessing and diagnostics.
-- 2) FYERS_SUCCESS_SYMBOLS stores successful SYMBOL + TRADING_DATE rows for daily-load auditability.
--
-- Notes:
-- - Resolution is fixed to 1D for this module.
-- - Success uniqueness is SYMBOL + TRADING_DATE.

CREATE TABLE FYERS_REUSE_SYMBOLS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INPUT_SYMBOL VARCHAR2(100),
    NORMALIZED_SYMBOL VARCHAR2(100),
    STATUS VARCHAR2(50),
    ERROR_CODE VARCHAR2(100),
    ERROR_MESSAGE VARCHAR2(4000),
    START_DATE DATE,
    END_DATE DATE,
    RESOLUTION VARCHAR2(10) DEFAULT '1D',
    RETRY_COUNT NUMBER DEFAULT 0,
    SOURCE VARCHAR2(50) DEFAULT 'FYERS_SINGLE_STOCK',
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT CK_FYERS_REUSE_RESOLUTION CHECK (RESOLUTION = '1D')
);

CREATE INDEX IDX_FYERS_REUSE_SYMBOLS_01
ON FYERS_REUSE_SYMBOLS (NORMALIZED_SYMBOL, STATUS);

CREATE INDEX IDX_FYERS_REUSE_SYMBOLS_02
ON FYERS_REUSE_SYMBOLS (CREATED_AT);

CREATE INDEX IDX_FYERS_REUSE_SYMBOLS_03
ON FYERS_REUSE_SYMBOLS (START_DATE, END_DATE);

CREATE TABLE FYERS_SUCCESS_SYMBOLS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SYMBOL VARCHAR2(100) NOT NULL,
    TRADING_DATE DATE NOT NULL,
    RESOLUTION VARCHAR2(10) DEFAULT '1D',
    INSERTED_ROWS NUMBER DEFAULT 0,
    DUPLICATE_ROWS_SKIPPED NUMBER DEFAULT 0,
    STATUS VARCHAR2(30) DEFAULT 'SUCCESS',
    SOURCE VARCHAR2(50) DEFAULT 'FYERS_SINGLE_STOCK',
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT UK_FYERS_SUCCESS_SYMBOLS UNIQUE (SYMBOL, TRADING_DATE),
    CONSTRAINT CK_FYERS_SUCCESS_RESOLUTION CHECK (RESOLUTION = '1D')
);

CREATE INDEX IDX_FYERS_SUCCESS_SYMBOLS_01
ON FYERS_SUCCESS_SYMBOLS (SYMBOL, TRADING_DATE);

CREATE INDEX IDX_FYERS_SUCCESS_SYMBOLS_02
ON FYERS_SUCCESS_SYMBOLS (TRADING_DATE, STATUS);
