PROMPT Creating NSE FFMC objects if they are missing.

DECLARE
  v_exists NUMBER := 0;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM USER_TABLES WHERE TABLE_NAME = 'CVING_NSE_FFMC_HIST';
  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE CVING_NSE_FFMC_HIST (
        ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        TRADE_DATE DATE NOT NULL,
        SYMBOL VARCHAR2(50) NOT NULL,
        SOURCE_NAME VARCHAR2(50) NOT NULL,
        SERIES VARCHAR2(10),
        SECURITY_NAME VARCHAR2(300),
        RAW_TOTAL_MCAP NUMBER(24,6),
        RAW_TOTAL_MCAP_UNIT VARCHAR2(30),
        TOTAL_MCAP_CR NUMBER(24,6),
        RAW_FFMC NUMBER(24,6),
        RAW_FFMC_UNIT VARCHAR2(30),
        FFMC_CR NUMBER(24,6),
        RESPONSE_PAYLOAD CLOB,
        FETCH_STATUS VARCHAR2(30) DEFAULT 'SUCCESS' NOT NULL,
        ERROR_MESSAGE VARCHAR2(2000),
        FETCH_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CREATED_BY VARCHAR2(128) DEFAULT USER NOT NULL,
        UPDATED_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT UQ_CVING_NSE_FFMC UNIQUE (TRADE_DATE, SYMBOL, SOURCE_NAME),
        CONSTRAINT CK_CVING_NSE_FFMC_STATUS CHECK (FETCH_STATUS IN ('SUCCESS', 'FAILED', 'PARTIAL', 'SKIPPED', 'PARSE_ERROR')),
        CONSTRAINT CK_CVING_NSE_FFMC_JSON CHECK (RESPONSE_PAYLOAD IS JSON OR RESPONSE_PAYLOAD IS NULL)
      ) TABLESPACE CVING_DATA
    ]';
  END IF;
END;
/

BEGIN
