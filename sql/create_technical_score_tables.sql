  SCORE_GRADE,
  SCORE_SOURCE,
  SCORE_BREAKDOWN_JSON,
  EMA20,
  EMA50,
  EMA100,
  EMA200,
  RSI14,
  MACD_HIST,
  ADX14,
  VOLUME_RATIO_20,
  DELIVERY_REL_20,
  ATH,
  HIGH_52W,
  LOW_52W,
  SUPPORT_LEVEL,
  RESISTANCE_LEVEL,
  RISK_FLAGS_JSON,
  MISSING_INPUTS_JSON,
  CREATED_AT,
  UPDATED_AT
FROM TECHNICAL_SCORE_LATEST;

COMMIT;
