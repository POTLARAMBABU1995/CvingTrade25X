BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IDX_TECH_SCORE_LATEST_DATE ON TECHNICAL_SCORE_LATEST (TRADING_DATE DESC)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IDX_TECH_SCORE_LATEST_SCORE ON TECHNICAL_SCORE_LATEST (SCORE_SORT DESC, TREND_SORT ASC)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IDX_TECH_SCORE_LATEST_TREND ON TECHNICAL_SCORE_LATEST (TREND, TREND_SORT)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
END;
/

MERGE INTO TECHNICAL_SCORE_CONFIG tgt
USING (
  SELECT 'near_high_pct' CONFIG_KEY, '5' CONFIG_VALUE, 'TREND' CONFIG_GROUP, 'Near ATH or 52W high threshold percent.' DESCRIPTION FROM dual UNION ALL
  SELECT 'near_low_pct', '5', 'TREND', 'Near 52W low threshold percent.' FROM dual UNION ALL
  SELECT 'near_level_pct', '2', 'STRUCTURE', 'Near support/resistance threshold percent.' FROM dual UNION ALL
  SELECT 'breakout_buffer_pct', '0.25', 'STRUCTURE', 'Resistance breakout buffer percent.' FROM dual UNION ALL
  SELECT 'breakdown_buffer_pct', '0.25', 'STRUCTURE', 'Support breakdown buffer percent.' FROM dual UNION ALL
  SELECT 'ema20_overextension_pct', '8', 'RISK', 'Distance above EMA20 risk threshold.' FROM dual UNION ALL
  SELECT 'atr_overextension_multiple', '2.5', 'RISK', 'ATR multiple above EMA20 risk threshold.' FROM dual UNION ALL
  SELECT 'low_volume_ratio20', '0.7', 'RISK', 'Low liquidity volume ratio threshold.' FROM dual
) src
ON (tgt.CONFIG_KEY = src.CONFIG_KEY)
WHEN MATCHED THEN UPDATE SET
  tgt.CONFIG_VALUE = src.CONFIG_VALUE,
  tgt.CONFIG_GROUP = src.CONFIG_GROUP,
  tgt.DESCRIPTION = src.DESCRIPTION,
  tgt.IS_ACTIVE = 'Y',
  tgt.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (
  CONFIG_KEY, CONFIG_VALUE, CONFIG_GROUP, DESCRIPTION, IS_ACTIVE
) VALUES (
  src.CONFIG_KEY, src.CONFIG_VALUE, src.CONFIG_GROUP, src.DESCRIPTION, 'Y'
);

