      SCORE_BREAKDOWN_JSON      CLOB,
      RISK_FLAGS_JSON           CLOB,
      MISSING_INPUTS_JSON       CLOB,
      CREATED_AT                TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_TECH_SCORE_HISTORY PRIMARY KEY (SYMBOL, TRADING_DATE, RUN_ID),
      CONSTRAINT CK_TECH_SCORE_HIST_RANGE CHECK (SCORE IS NULL OR SCORE BETWEEN 0 AND 100),
